import assert from 'node:assert/strict';

export async function testModelWorkspace(page,command,modelPath) {
  const initial=(await command({type:'snapshot'})).document;
  await page.getByRole('button',{name:'Rig',exact:true}).click();
  await page.locator('#model-workspace').click();
  await page.locator('#model-bones button').nth(2).waitFor();
  assert.equal(await page.locator('#model-bones button').count(),3);
  assert(Number(await page.locator('#model-capacity').getAttribute('data-capacity'))>=3,'Actual linked GPU capacity was not measured');
  assert.deepEqual((await command({type:'snapshot'})).document,initial,'Workspace selection dirtied the model');
  await page.locator('#model-bone-overlay g[data-overlay-bone="1"]').click();
  assert.equal(await page.locator('#model-bone-name').inputValue(),'Left');
  assert.deepEqual((await command({type:'snapshot'})).document,initial,'Bone picking moved a layer or changed content');
  await page.locator('#model-bones button[data-bone="2"]').click();
  await page.locator('#model-bone-name').fill('Wing');
  const renamed=(await command({type:'snapshot'})).document;
  assert.match(renamed.resourceOverrides[modelPath],/^[a-f0-9]{64}$/,'Unblurred model input did not reach resource history');
  assert.equal(await page.locator('#model-bone-name').inputValue(),'Wing');
  await command({type:'undo'});await page.locator('#model-bones').getByRole('button',{name:'Right',exact:true}).waitFor();
  await command({type:'redo'});await page.locator('#model-bones').getByRole('button',{name:'Wing',exact:true}).waitFor();await command({type:'undo'});
  await page.locator('#model-bones button[data-bone="1"]').click();
  await page.locator('#model-bone-parent').selectOption('2');await page.locator('#model-bone-apply').click();
  await command({type:'snapshot'});assert.deepEqual(await page.locator('#model-bones button').allTextContents(),['Root','Right','Left']);
  await command({type:'undo'});
  await page.locator('#model-create').click();await page.locator('#model-new-name').fill('Tip');await page.locator('#model-new-ty').fill('20');
  await page.locator('#model-new-confirm').click();await command({type:'snapshot'});
  assert.equal(await page.locator('#model-bones button').count(),4);
  const beforeCancel=(await command({type:'snapshot'})).document;await page.locator('#model-delete').click();
  await page.locator('#model-delete-cancel').click();assert.deepEqual((await command({type:'snapshot'})).document,beforeCancel);
  await page.locator('#model-delete').click();await page.locator('#model-delete-confirm').click();await command({type:'snapshot'});
  assert.equal(await page.locator('#model-bones button').count(),3);await command({type:'undo'});
  await page.locator('#model-bones button').nth(3).waitFor();assert.equal(await page.locator('#model-bones button').count(),4);await command({type:'undo'});
  await page.locator('#model-bones button[data-bone="2"]').click();await page.locator('#model-delete').click();
  assert.equal(await page.locator('#model-delete-replacement').isVisible(),true);await page.locator('#model-delete-replacement').selectOption('0');
  await page.locator('#model-delete-confirm').click();await command({type:'snapshot'});assert.equal(await page.locator('#model-bones button').count(),2);await command({type:'undo'});
  await page.locator('#model-skin-mesh').selectOption('1');await page.locator('#model-vertex').fill('0');await page.locator('#model-vertex').dispatchEvent('change');
  const canvas=page.locator('#canvas canvas'),before=await canvas.screenshot();
  await page.locator('#model-joint-0').selectOption('1');await page.locator('#model-weight-0').fill('1');
  const frozen=await command({type:'freeze'});assert(frozen.document.resourceOverrides[modelPath]);
  await command({type:'thaw'});assert.notDeepEqual(await canvas.screenshot(),before,'User numeric weights did not deform the real mesh');
  await command({type:'undo'});assert.deepEqual(await canvas.screenshot(),before);
  const clean=(await command({type:'snapshot'})).document;
  await page.locator('#model-weight-0').fill('0');await assert.rejects(command({type:'snapshot'}),/positive/i);
  await assert.rejects(command({type:'add-image',image:{name:'Blocked',model:'models/editor/rig.json',width:100,height:30}}),/positive/i);
  await page.locator('#timeline-toggle').click();await page.locator('#timeline-create').click();
  await page.getByRole('alert').filter({hasText:/positive/i}).waitFor();
  await page.locator('#model-weights-revert').click();assert.deepEqual((await command({type:'snapshot'})).document,clean);
  await page.locator('#timeline-create').click();await command({type:'snapshot'});
  await page.locator('.timeline-key[data-channel="0"][data-frame="0"]').click();
  await page.locator('#timeline-key-value').fill('335');await page.locator('#model-weight-0').fill('0');
  await page.locator('#timeline-key-editor button[type="submit"]').click();await page.getByRole('alert').filter({hasText:/positive/i}).waitFor();
  await page.locator('#model-weights-revert').click();await page.locator('#timeline-revert').click();
  assert.equal((await command({type:'snapshot'})).document.scene.objects[0].origin.animation.c0[0].value,320,'Key editor bypassed an invalid model draft');
  await page.locator('#timeline-key-value').fill('330');await page.locator('#model-bone-name').fill('Kept draft');await page.locator('#model-bone-apply').click();
  await page.locator('#model-bones').getByRole('button',{name:'Kept draft',exact:true}).waitFor();
  assert.equal(await page.locator('#timeline-key-value').inputValue(),'330','Resource edit erased the independent property draft');
  assert.equal((await command({type:'snapshot'})).document.scene.objects[0].origin.animation.c0[0].value,330);
  await page.locator('#timeline-toggle').click();
  await page.locator('#properties-workspace').click();await page.locator('#model-workspace').click();
  await page.locator('#model-bones button').nth(2).waitFor();
  await command({type:'load',document:initial});
  await page.locator('#model-bones button[data-bone="2"]').click();await page.locator('#model-bone-name').fill('Wing');await page.locator('#model-bone-apply').click();
  const authored=(await command({type:'snapshot'})).document;
  await page.locator('#properties-workspace').click();
  console.log('Model workspace: native forms, real GPU capacity, hierarchy, confirmation/cancel, weight pixels, drafts/freeze and resource history passed');
  return authored;
}
